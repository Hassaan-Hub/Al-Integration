import { Clock3, ListChecks, Sparkles, Type } from 'lucide-react';
import { PriorityBadge } from '../ui/PriorityBadge';

export const PlanResult = ({ plan }) => {
  if (!plan) {
    return null;
  }

  return (
    <section className="rounded-2xl border border-slate-200 bg-white shadow-sm" aria-live="polite">
      <header className="flex flex-wrap items-center justify-between gap-3 border-b border-slate-200 bg-slate-50/70 px-5 py-4">
        <div className="flex items-center gap-2">
          <span className="inline-flex size-8 items-center justify-center rounded-lg bg-brand-50 text-brand-600">
            <Sparkles className="size-4" aria-hidden="true" />
          </span>
          <h2 className="text-sm font-semibold text-slate-900">Generated plan</h2>
        </div>

        <div className="flex flex-wrap items-center gap-2">
          <PriorityBadge priority={plan.priority} />
          <span className="inline-flex items-center gap-1.5 rounded-full bg-white px-2.5 py-1 text-xs font-medium text-slate-700 ring-1 ring-inset ring-slate-200">
            <Clock3 className="size-3.5 text-slate-400" aria-hidden="true" />
            {plan.estimatedHours !== null ? `${plan.estimatedHours} estimated hours` : 'No estimate'}
          </span>
        </div>
      </header>

      <div className="space-y-6 px-5 py-5">
        <div>
          <div className="flex items-center gap-2 text-xs font-semibold uppercase tracking-wide text-slate-400">
            <Type className="size-3.5" aria-hidden="true" />
            Summary
          </div>
          <p className="mt-2 text-sm leading-6 text-slate-700">{plan.summary}</p>
        </div>

        <div>
          <div className="flex items-center gap-2 text-xs font-semibold uppercase tracking-wide text-slate-400">
            <ListChecks className="size-3.5" aria-hidden="true" />
            Action steps
          </div>

          {plan.steps.length === 0 ? (
            <p className="mt-2 text-sm text-slate-500">The assistant did not return any action steps.</p>
          ) : (
            <ol className="mt-3 space-y-2.5">
              {plan.steps.map((step, index) => (
                <li
                  key={`${index}-${step}`}
                  className="flex items-start gap-3 rounded-lg border border-slate-200 bg-white px-3.5 py-3"
                >
                  <span className="inline-flex size-6 shrink-0 items-center justify-center rounded-full bg-brand-50 text-xs font-semibold text-brand-700">
                    {index + 1}
                  </span>
                  <span className="text-sm leading-6 text-slate-700">{step}</span>
                </li>
              ))}
            </ol>
          )}
        </div>
      </div>

      <footer className="border-t border-slate-200 bg-slate-50/70 px-5 py-3">
        <p className="text-xs text-slate-500">
          This plan was generated by the AI service. It has not been saved as a task — copy the steps into a new
          task when you are ready.
        </p>
      </footer>
    </section>
  );
};
